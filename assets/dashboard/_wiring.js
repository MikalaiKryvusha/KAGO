const FREEZE_MS = 3000;   // столько без пульса — и это уже тревога, а не задержка
const RETRY_MS  = 1000;   // через столько страница сама пробует подцепиться заново

const $ = (id) => document.getElementById(id);
// Шапка — тоже утверждение. Пишется через одну функцию, чтобы у неё был один автор.
const head = (text) => { const e = $('head-what'); if (e && e.textContent !== text) e.textContent = text; };
const fmt = (v, unit, digits = 0) => (v === null || v === undefined ? '—' : `${Number(v).toFixed(digits).replace('.', ',')} ${unit}`);
const hms = (ms) => {
  const t = Math.max(0, Math.floor(ms / 1000));
  const p2 = (n) => String(n).padStart(2, '0');
  return `${Math.floor(t / 3600)}:${p2(Math.floor(t / 60) % 60)}:${p2(t % 60)}`;
};
const seg = (id, v, width) => {
  const el = $(id);
  if (!el) return;
  el.textContent = (v === null || v === undefined) ? '-'.repeat(width) : String(Math.round(v));
};

let pulse = null;         // последний пришедший пульс
let pulseAt = 0;          // когда он пришёл, по часам БРАУЗЕРА (часы прогона могли встать)
let es = null;            // сама лента; её `readyState` — единственный честный ответ «связь есть?»
let linkLostAt = 0;       // когда связь пропала, по часам браузера

/* 🔴 СВЯЗЬ — ОТДЕЛЬНЫЙ ФАКТ, И СТРАНИЦА ОБЯЗАНА ЕГО ЗНАТЬ (`bugs/27`).
   Судим по состоянию самой ленты, а не по тишине: тишина законна (между прогонами прибору нечего
   сказать часами), а вот `readyState !== OPEN` означает ровно одно — сервера на том конце нет.
   Пока связи нет, страница не имеет права рисовать данные так, будто они текущие. */
const linkUp = () => es !== null && es.readyState === 1;   // 1 = OPEN

/* Принятые ключевые кадры крутятся СВОИМ ходом, от начала загрузки страницы и до её конца. Часы у
   них никто не отбирает — см. правило владельца в шапке. Отсюда удалена функция `seizeAnimations`,
   которая ставила их на паузу, чтобы выдавать время вручную. */

function paint() {
  if (!pulse) return;
  const r = pulse.run || {};
  const c = pulse.card || {};

  $('f-freq').textContent = r.frequencyMhz ? `${r.frequencyMhz} МГц` : '—';
  $('f-volt').textContent = r.voltageMv ? `${r.voltageMv} мВ` : '—';
  $('f-depth').innerHTML = (r.stockVoltageMv && r.depthMv !== null && r.depthMv !== undefined)
    ? `сток ${r.stockVoltageMv} · андервольт <b style="display:inline;font-size:13px;color:var(--ok)">−${r.depthMv} мВ</b>`
    : '';
  const p = r.probe || {};
  $('f-probe').innerHTML = `${(p.elapsedSeconds ?? 0).toFixed(1).replace('.', ',')} `
    + `<span style="font-size:17px;color:var(--dim)">из ${p.totalSeconds ?? 10} с</span>`;
  $('f-band').textContent = r.band || '—';
  const cov = r.coverage || {};
  // «Ступеней пройдено» УБРАНО словом владельца: ступень спуска по напряжению — внутренняя единица
  // движка, и оператору она не говорит ничего, ровно как убранная раньше «ступень N из M».
  // Осталось то, что говорит: сколько частот диапазона уже настроено.
  // ГДЕ ИДЁТ ФРОНТ — первое, что спросил владелец, глядя на прогон. Спуск идёт СВЕРХУ ВНИЗ (его
  // алгоритм, ideas/03 §6), поэтому положение — это доля пройденного пути от верхней частоты к нижней.
  const front = r.frequencyMhz;
  let walked = '';
  if (front && r.bandFromMhz && r.bandToMhz && r.bandFromMhz > r.bandToMhz) {
    const pct = Math.round(100 * (r.bandFromMhz - front) / (r.bandFromMhz - r.bandToMhz));
    walked = `<span style="white-space:nowrap">спустились до <b style="display:inline;font-size:13px">${front} МГц</b> — это ${pct} % пути</span><br>`;
  }
  $('f-cov').innerHTML = cov.total
    ? walked + `<span style="white-space:nowrap">настроено частот <b style="display:inline;font-size:13px">${cov.closed ?? 0} из ${cov.total}</b></span>`
    : walked;

  seg('seg-clk', c.clockMhz, 4);
  seg('seg-temp', c.tempC, 2);
  seg('seg-fan', c.fanPct, 2);
  seg('seg-pwr', c.powerW, 3);
  $('synthetic-note').style.display = c.synthetic ? 'inline-block' : 'none';

  // ДВОЕ ЧАСОВ. Таймер прогона идёт ОТ ПУЛЬСА — значит замирает вместе с прогоном и показывает,
  // на какой секунде тот встал; стенные часы идут сами. Их расхождение и есть «давно ли встало».
  $('c-elapsed').textContent = hms(pulse.runMs);

  $('state-alive').textContent = `● ${r.state || 'ПРОГОН'}`;
  document.title = r.finished
    ? 'KAGO — прогон завершён'
    : 'KAGO — Выполняется автоматический тюнинг-прогон видеокарты';
}

/* Кадр. Всё, что здесь считается, считается ОТ ПУЛЬСА. */
function frame() {
  requestAnimationFrame(frame);

  // 🔴 СВЯЗЬ СУДИТСЯ ПЕРВОЙ, И ЕЁ ОТСУТСТВИЕ НЕ ЗАГЛУШАЕТСЯ НИЧЕМ (`bugs/27`).
  //
  // Порядок здесь и есть лечение. Ниже стоит `frozen`, у которого стоит `!pulse.run.finished`, —
  // и на штатном финале он выключал ВСЮ диагностику страницы: сервер уходил вместе с прогоном, а
  // окно оставалось навсегда с последними числами и живыми стенными часами. Оно выглядело зависшим,
  // не имея права так сказать. Требование владельца 2026-08-22 дословно: «НИЧТО НЕ ДОЛЖНО ЕГО
  // ДЕРЖАТЬ В ЗАВИСШЕМ СОСТОЯНИИ… единственное — смерть ОС, но не программно».
  //
  // ТРИ РАЗНЫХ СОСТОЯНИЯ, И ОНИ НЕ ОДНО И ТО ЖЕ. Тревога поднимается ТОЛЬКО там, где связь оборвалась
  // под ИДУЩИМ прогоном: это и есть случай, ради которого прибор заведён (машина умерла вместе с
  // процессом). Штатный финал и ожидание прогона — не тревога, и кричать на них значит обесценить
  // крик к тому разу, когда он будет настоящим.
  if (!linkUp()) {
    const goneS = linkLostAt ? Math.round((performance.now() - linkLostAt) / 1000) : 0;
    const liveRunLost = pulse && !pulse.noRun && pulse.run && pulse.run.finished !== true;
    document.body.classList.toggle('hung', Boolean(liveRunLost));
    if (liveRunLost) {
      $('state-dead').textContent = `■ СВЯЗЬ С ПРОГОНОМ ОБОРВАЛАСЬ ${goneS} с назад — числа ниже уже не текущие`;
      head('Связь с прогоном потеряна — окно показывает последнее, что успело прийти');
      document.title = 'KAGO — связь с прогоном потеряна';
    } else {
      $('state-alive').textContent = pulse && pulse.run && pulse.run.finished
        ? '● ПРОГОН ЗАВЕРШЁН — окно отцепилось от прогона и ждёт следующего'
        : '● НЕТ СВЯЗИ С ПРОГОНОМ — окно ждёт и подключается само';
      head('Прогон не запущен — окно ждёт');
      document.title = 'KAGO — нет связи с прогоном';
    }
    return;
  }

  if (!pulse) return;
  // ВОЗРАСТ ЗАПИСИ + СОБСТВЕННОЕ ОЖИДАНИЕ. Второе слагаемое очевидно, первое — нет, и без него окно
  // лгало: открытое между прогонами, оно получало прибор ПРОШЛОГО прогона и, только что его получив,
  // считало секундной давности. Владелец увидел это сразу: «запустилось в состоянии прогон оставлен».
  // Сервер теперь присылает настоящий возраст записи, и отсчёт идёт от него.
  const since = (Number(pulse.ageMs) || 0) + (performance.now() - pulseAt);

  // ПРОГОНА НЕТ — это ОТДЕЛЬНОЕ состояние, а не «зависший прогон». Пустой прибор означает, что не
  // идёт ничего; рисовать по нему тревогу значило бы обесценить тревогу ещё одним способом.
  if (pulse.noRun) {
    document.body.classList.remove('hung');
    $('state-alive').textContent = `● ПРОГОНА НЕТ — ${pulse.run.note || 'ожидание запуска'}`;
    // ШАПКА ТОЖЕ УТВЕРЖДЕНИЕ, а не украшение. В макете «Выполняется автоматический тюнинг-прогон»
    // верно по условию; на живой странице это ЛОЖЬ всякий раз, когда прогона нет — и владелец
    // увидел её крупными буквами прямо над панелью «ПРОГОНА НЕТ». Один экран не может говорить
    // двух разных вещей: на что упадёт взгляд, то человек и прочтёт.
    head('Прогон не запущен — окно ждёт');
    document.title = 'KAGO — прогона нет';
    return;
  }
  head('Выполняется автоматический тюнинг-прогон видеокарты');

  // Прогон, который ЗАКОНЧИЛСЯ, не должен выглядеть зависшим — иначе тревога обесценится в первый же
  // штатный финал, и оператор перестанет ей верить.
  // СКОЛЬКО МОЛЧАНИЯ СЕЙЧАС НОРМАЛЬНО — говорит САМ ПРОГОН, а не гадает страница.
  //
  // Он блокируется на время стресс-теста: нагрузка запускается синхронно, и десять секунд из процесса
  // не выходит НИЧЕГО — ни по SSE, ни по сокету, потому что стоит цикл событий, а не транспорт.
  // Со старым фиксированным терпением в 3 с тревога загоралась НА КАЖДОЙ ступени, все 68 раз за
  // прогон. Тревога, которая врёт по расписанию, отменяет сама себя — и настоящее зависание,
  // ради которого она заведена, оператор уже не отличит.
  //
  // Поэтому прогон перед прожигом объявляет свой бюджет молчания (`quietMs`), и страница судит по
  // нему. Молчание В ПРЕДЕЛАХ объявленного — это прожиг, и так и написано. Молчание СВЕРХ него —
  // это зависание, и написано будет это. Оба утверждения правдивы.
  const quiet = Number(pulse.quietMs) > 0 ? Number(pulse.quietMs) : FREEZE_MS;
  const frozen = !pulse.run.finished && since > quiet;
  document.body.classList.toggle('hung', frozen);
  const r = pulse.run;
  if (frozen) {
    // ПЕРЕБРАЛ СВОЙ ЖЕ БЮДЖЕТ. Насколько именно — на экране: «встало 4 секунды назад» и «встало три
    // минуты назад» требуют от оператора разных действий.
    $('state-dead').textContent = r.frequencyMhz
      ? `■ ЗАМЕРЛО на ${((since - quiet) / 1000).toFixed(0)} с сверх ожидаемого — ${r.frequencyMhz} МГц / ${r.voltageMv ?? '?'} мВ`
      : '■ ЗАМЕРЛО';
  } else if (!r.finished && quiet > FREEZE_MS) {
    // ИДЁТ ПРОЖИГ, и это ЖИВОЕ состояние.
    // СЧЁТЧИК СЕКУНД ОТСЮДА УБРАН — слово владельца 2026-08-16 23:3x, глядя на живой прогон:
    // «● ИДЁТ СТРЕСС-ТЕСТ — 10 с из 10 · Тут нужно убрать секунд счётчик». Строка состояния отвечает
    // на вопрос «что сейчас происходит», а не «сколько осталось»: секунды ползли до потолка и там
    // стояли, то есть большую часть времени показывали «10 из 10» и не значили ничего.
    // Прогресс пробы остался там, где ему место — в своём виджете (`f-probe`).
    $('state-alive').textContent = `● ${r.state || 'ПРОГОН'}`;
  }

  // Здесь стояла подстановка времени в кадры — `a.currentTime = pulse.runMs + поводок`. Удалена
  // словом владельца: кадры идут своим ходом и не зависят ни от чего, что может замолчать.
}

function connect() {
  es = new EventSource('/live');
  es.onopen = () => { linkLostAt = 0; };
  es.onmessage = (m) => {
    linkLostAt = 0;
    try { pulse = JSON.parse(m.data); } catch (e) { return; }
    pulseAt = performance.now();
    paint();
  };
  // 🔴 РАЗРЫВ — ЭТО НЕ «ВСЁ ХОРОШО», И ЭТО НЕ «МОЛЧАНИЕ» (`bugs/27`).
  //
  // Здесь стоял пустой обработчик с расчётом на то, что тишину поймает сторож `FREEZE_MS`. Он её не
  // ловит: сторож заглушён у ЗАВЕРШЁННОГО прогона (см. `frozen` ниже), а прогон завершается штатно
  // каждый раз. Владелец получал вечно застывшую страницу с тикающими стенными часами — и никакого
  // способа у неё сказать, что сервера больше нет.
  //
  // Теперь разрыв — состояние, которое НАЗЫВАЕТСЯ, и страница из него САМА ВЫХОДИТ: `EventSource`
  // переподключается, пока может, а когда сдаётся (`CLOSED`), за него не переподключается никто —
  // поэтому пробуем сами. Новый прогон поднимет сервер, и окно оживёт без человека.
  es.onerror = () => {
    if (!linkLostAt) linkLostAt = performance.now();
    if (es.readyState === 2) { try { es.close(); } catch (e) { /* и так закрыт */ } setTimeout(connect, RETRY_MS); }
  };
}

/* ==================================================================================================
   ЗВУК — второй канал обратной связи (`homeworks/04`, движок в `_sound.js`)
   ==================================================================================================
   Звук НИЧЕМ не обусловлен: он идёт, пока открыто окно и включён, и доказывает, что жива МАШИНА.
   Что встал прогон — говорят слова, цвет и остановка колец живого знака. Это то же правило, что и
   у анимации, и по той же причине.

   ВЫБОР ЧЕЛОВЕКА ЗАПОМИНАЕТСЯ. Окно поднимается заново на каждый прогон, а прогонов за вечер
   бывает десяток: заставлять владельца каждый раз включать звук и выбирать тему значит гарантированно
   довести его до того, что он выключит звук навсегда. Хранится в `localStorage` — он переживает
   перезапуск окна и не уезжает никуда за пределы этой машины.

   ПРОГОН НАЧИНАЕТСЯ СО ЗВУКОМ — слово владельца 2026-08-22: «прогон должен начинаться с включенным
   звуком, который плавно за 20 секунд нарастает по громкости от 0 до 100 %». Раньше здесь стояло
   обратное правило («звук не поднимается сам»), и оно было не принципом, а КАПИТУЛЯЦИЕЙ перед
   политикой автозапуска браузера. Политика снята в самом окне: мы поднимаем СВОЙ Edge в СВОЁМ
   профиле и передаём ему `--autoplay-policy=no-user-gesture-required` (`run-dashboard.mjs`).

   ДВА ФАКТА ВМЕСТО ОДНОГО. `on` — намерение страницы, `KagoSound.running` — звучит ли оно на самом
   деле. Если окно открыли в обычном браузере владельца, где флага нет, контекст останется усыплённым:
   тогда страница НЕ ВРЁТ кнопкой «ЗВУК ВКЛ» в тишине, а честно говорит, что ждёт щелчка, и стартует
   от первого же прикосновения к странице — любого, включая открытие этого самого меню.

   ЯВНОЕ «ВЫКЛ» СИЛЬНЕЕ АВТОЗАПУСКА. Умолчание стало «включено», но если владелец выключил звук
   руками, окно поднимется молча: выключатель, который сам себя возвращает, — это не выключатель. */
const SND_KEY = 'kago.sound';
const SND_FADE_SECONDS = 20;                 // слово владельца, дословно
const sndLoad = () => {
  try { return JSON.parse(localStorage.getItem(SND_KEY)) || {}; } catch (e) { return {}; }
};
const sndSave = (o) => { try { localStorage.setItem(SND_KEY, JSON.stringify(o)); } catch (e) { /* приватный режим */ } };

function wireSound() {
  const btn = $('snd-btn'), lbl = $('snd-lbl'), sel = $('snd-theme'), work = $('snd-work'), move = $('snd-move');
  if (!btn || typeof KagoSound === 'undefined') return;      // страница собрана без звука — не падаем
  const saved = sndLoad();
  if (Number.isFinite(saved.theme)) sel.value = String(saved.theme);
  if (typeof saved.work === 'boolean') work.checked = saved.work;

  const dot = $('viz-dot'), vizBtn = $('viz-btn');
  const paint = () => {
    const waiting = KagoSound.on && !KagoSound.running;
    // Зелёный обод означает ЗВУЧИТ, а не «намерены звучать»: гореть зелёным под надписью «ждёт
    // щелчка» значит обещать цветом то, чего нет, — а цвет читают раньше слов.
    btn.classList.toggle('on', KagoSound.on && KagoSound.running);
    lbl.textContent = !KagoSound.on ? 'ЗВУК ВЫКЛ' : (waiting ? 'ЗВУК ЖДЁТ ЩЕЛЧКА' : 'ЗВУК ВКЛ');
    if (!KagoSound.on) move.textContent = '';
    // Закрытое меню обязано само говорить, звучит ли оно: иначе за ответом надо лезть внутрь.
    if (vizBtn) vizBtn.classList.toggle('on', KagoSound.on && KagoSound.running);
    if (dot) dot.title = lbl.textContent;
  };
  const remember = () => sndSave({ on: KagoSound.on, theme: Number(sel.value), work: work.checked });

  KagoSound.onMove((t) => { if (KagoSound.on) move.textContent = t; });

  /** Пустить звук и подать его громкость плавно. Одна дверь для автозапуска и для щелчка. */
  const start = (fade) => {
    KagoSound.toggle(true);
    KagoSound.setTheme(Number(sel.value));
    KagoSound.setWork(work.checked);
    if (fade) KagoSound.fadeIn(SND_FADE_SECONDS);
    paint();
  };

  btn.addEventListener('click', () => {
    if (KagoSound.on && KagoSound.running) { KagoSound.toggle(false); paint(); }
    else start(!KagoSound.running);          // подача нужна только когда звук ПОЯВЛЯЕТСЯ
    remember();
  });
  sel.addEventListener('change', () => { KagoSound.setTheme(Number(sel.value)); remember(); });
  work.addEventListener('change', () => { KagoSound.setWork(work.checked); remember(); });

  /* АВТОЗАПУСК. Умолчание — включено; выключено только если владелец сам так решил. */
  if (saved.on !== false) {
    start(true);
    if (!KagoSound.running) {
      // Контекст усыплён: просим разбудить, а если браузер откажет — ждём первого прикосновения.
      KagoSound.resume().then((ok) => {
        if (ok) { KagoSound.fadeIn(SND_FADE_SECONDS); }
        paint();
      });
      const wake = () => {
        if (!KagoSound.on) return;
        KagoSound.resume().then(() => { KagoSound.fadeIn(SND_FADE_SECONDS); paint(); });
      };
      document.addEventListener('pointerdown', wake, { once: true });
      document.addEventListener('keydown', wake, { once: true });
    }
  }
  paint();
}

/* ==================================================================================================
   МЕНЮ ВИЗУАЛИЗАТОРА — одна кнопка в углу, слово владельца 2026-08-22
   ==================================================================================================
   «всё управление звука нужно поместить в меню, которое одной кнопкой сведено в том углу… Кликом
   меню как drop-down меню раскрывается и там управление визуализатором, в частности, раздел звука».

   Меню закрывается щелчком мимо и клавишей Esc. Это не вежливость: орган, который закрывается
   только повторным попаданием в ту же кнопку, на живом прогоне остаётся раскрытым и загораживает
   правую колонку — ровно ту, ради которой окно и открыто. */
function wireVizMenu() {
  const btn = $('viz-btn'), pop = $('viz-pop');
  if (!btn || !pop) return;                                  // страница собрана без меню — не падаем
  const setOpen = (open) => {
    pop.hidden = !open;
    btn.setAttribute('aria-expanded', open ? 'true' : 'false');
  };
  btn.addEventListener('click', (e) => { e.stopPropagation(); setOpen(pop.hidden); });
  pop.addEventListener('click', (e) => e.stopPropagation());
  document.addEventListener('click', () => setOpen(false));
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape') setOpen(false); });
  setOpen(false);
}

/* Стенные часы браузера — единственное на этой странице, что НЕ приходит с прогона, и это
   намеренно: они обязаны идти, когда всё остальное встало. */
function wallClock() {
  const d = new Date();
  const p2 = (n) => String(n).padStart(2, '0');
  $('c-now').textContent = `${p2(d.getHours())}:${p2(d.getMinutes())}:${p2(d.getSeconds())}`;
}
wallClock();
