const RE_DATE_DOT = /(\d{2})\.(\d{2})\.(\d{4})/u;

/**
 * Запас на часовой пояс, в СУТКАХ. Дата дальше этого запаса в будущем наблюдением быть не могла.
 *
 * ⚠️ ЧИСЛО ВЫБРАНО В СТОРОНУ МОЛЧАНИЯ СТОРОЖА, И ЭТО НЕ НЕБРЕЖНОСТЬ. Машина владельца стоит в
 * `+03:00`, прогон может случиться в другом поясе, и «завтра» по календарю сторожа бывает
 * «сегодня» по календарю автора. Ложная тревога на здоровом дереве в этом проекте оплачена
 * ТРИЖДЫ (`bugs/75`), пропуск даты «завтра» — не оплачен ничем. Сутки не объясняются никаким
 * поясом, значит дальше суток — уже не пояс, а выдумка.
 *
 * @fork future-date-grace-window
 * OPTIONS:  строго «не позже сегодня» · сутки запаса · трое суток · вовсе не проверять будущее
 * COST:     ложная тревога на здоровом дереве (оплачена трижды, `bugs/75`) либо пропущенная
 *           поддельная дата, которая выглядит в ревью честнее, чем `NOT YET`
 * RECON:    NOT YET — разведки не было. Число выбрано рассуждением о часовых поясах, а не
 *           изучением того, как это решают другие. Долг признан и виден
 * DECIDED:  сутки — в сторону МОЛЧАНИЯ сторожа: цена ложной тревоги в проекте измерена,
 *           цена пропуска даты «завтра» — нет. Обе стороны границы стоят в наборе (оси X и P16)
 */
const FUTURE_GRACE_DAYS = 1;

/**
 * Разобрать дату наблюдения из значения поля. Возвращает `null`, если даты нет вовсе;
 * `{ valid: false }`, если она есть по форме, но такого дня не существует.
 *
 * Зачем существует (bugs/81). Правило R7 спрашивало у строки «похожа ли ты на дату» и на этом
 * останавливалось. `2099-01-01`, `2026-13-45` и `0000-00-00` проходили ворота молча — то есть
 * механизм, заведённый против недоказуемого «доказан», делал поддельную дату УДОБНЕЕ честного
 * `NOT YET`. Сторож был доказан против модели угрозы («строка, не похожая на дату») вместо самой
 * угрозы («заявление о наблюдении, которого не было») — тот же класс, который чинит весь эпик 76.
 */
export function parseObservationDate(value) {
  const s = String(value);
  let y; let m; let d;
  const iso = RE_DATE_ISO.exec(s);
  if (iso) { [, y, m, d] = iso; } else {
    const dot = RE_DATE_DOT.exec(s);
    if (!dot) return null;
    [, d, m, y] = dot;
  }
  const Y = Number(y); const M = Number(m); const D = Number(d);
  const dt = new Date(Y, M - 1, D);
  // Сверка обратным чтением: `new Date(2026, 12, 45)` молча уезжает в другой месяц, а не падает.
  const valid = M >= 1 && M <= 12 && D >= 1
    && dt.getFullYear() === Y && dt.getMonth() === M - 1 && dt.getDate() === D;
  return { text: iso ? iso[0] : `${d}.${m}.${y}`, valid, date: valid ? dt : null };
}

/** Лежит ли день дальше запаса в будущем. `now` вынесен параметром, чтобы фикстуры не зависели от календаря. */
export function isFutureDate(dt, now = new Date()) {
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const limit = new Date(today.getFullYear(), today.getMonth(), today.getDate() + FUTURE_GRACE_DAYS);
  return dt.getTime() > limit.getTime();
}

/** Снять префиксы комментариев, чтобы блок читался одинаково в `.mjs`, `.md` и `.ps1`. */
function strip(line) {
  return String(line)
    .replace(/^﻿/u, '')
    .replace(/^[\s]*(\/\/+|\/\*+|\*+\/?|#+|>+|--+)\s?/u, '')
    .replace(/\s*\*\/\s*$/u, '')
    .replace(/\r$/u, '')
    .trim();
}

/**
 * Разобрать текст в блоки. Блок начинается маркером и тянется, пока строки несут поля или их
 * продолжения; пустая строка или новый маркер его закрывают.
 *
 * Продолжение поля (строка без `ПОЛЕ:`, но непустая) приписывается ПРЕДЫДУЩЕМУ полю — иначе
 * длинное объяснение угрозы пришлось бы писать в одну строку, а этого никто делать не станет.
 */
export function parseBlocks(text) {
  const lines = String(text).split('\n');
  const blocks = [];
  let cur = null;
  const close = () => { if (cur) blocks.push(cur); cur = null; };

  for (let i = 0; i < lines.length; i++) {
    const raw = strip(lines[i]);
    const m = RE_MARKER.exec(raw);
    if (m) { close(); cur = { kind: m[1], name: m[2], line: i + 1, fields: [], }; continue; }
    if (!cur) continue;
    if (raw === '') { close(); continue; }
    const f = RE_FIELD.exec(raw);
    if (f) { cur.fields.push({ key: f[1], value: f[2].trim(), line: i + 1 }); continue; }
    // Продолжение предыдущего поля.
    if (cur.fields.length) {
      const last = cur.fields[cur.fields.length - 1];
      last.value = `${last.value} ${raw}`.trim();
      continue;
    }
    close();
  }
  close();
  return blocks;
}

/**
 * Проверить один блок. Возвращает список нарушений — по одному на каждую отдельную причину.
 *
 * Каждое нарушение несёт `field` — ПОЛЕ, из-за которого оно возникло. Поле здесь не украшение
 * отчёта: по нему выводится механизм, к которому относится фикстура (`MECH_OF_FIELD` ниже), и
 * благодаря этому доля механизма в наборе СЧИТАЕТСЯ ПРОГОНОМ, а не объявляется автором.
 * До 2026-08-30 имя поля жило только внутри человеческой фразы `why`, и счётчику пришлось бы
 * выковыривать его регулярным выражением из текста — прибор, читающий прозу, ломается от правки
 * этой прозы и молча начинает считать не то (`plans/77` §1).
 */
function reconDocExists(ref) {
  // Понимает КОНВЕНЦИЮ ПРОЕКТА, а не только точный путь: документы зовутся `NN_длинный-слаг.md`,
  // а ссылаются на них номером — `researches/27`. Правило, требующее точного имени файла,
  // краснело бы на каждой законной ссылке в проекте. Поймано первым же прощупыванием: законный
  // блок пошёл красным, и это был дефект ПРАВИЛА, а не блока.
  if (existsSync(join(ROOT, ref)) || existsSync(join(ROOT, `${ref}.md`))) return true;
  const m = /^([A-Za-z0-9_.-]+)\/(\d+)$/u.exec(ref);
  if (!m) return false;
  try {
    return readdirSync(join(ROOT, m[1])).some((f) => f.startsWith(`${m[2]}_`));
  } catch { return false; }
}

export function checkBlock(block, file = '<memory>', { now = new Date() } = {}) {
  const out = [];
  const add = (rule, field, why, line = block.line) =>
    out.push({ rule, field, file, line, name: block.name, kind: block.kind, why });
  const required = REQUIRED[block.kind] || [];
  const seen = new Map();

  for (const f of block.fields) {
    if (seen.has(f.key)) add('R5-duplicate', f.key, `поле «${f.key}» объявлено дважды`, f.line);
    else seen.set(f.key, f);
  }

  for (const key of required) {
    const f = seen.get(key);
    if (!f) { add('R1-missing', key, `нет обязательного поля «${key}»`); continue; }
    const v = f.value.trim();
    if (v === '') { add('R2-empty', key, `поле «${key}» пустое — «нет зазора» пишется словом, а не пустотой`, f.line); continue; }
    // Сверка идёт по НОРМАЛИЗОВАННОМУ значению (bugs/82): `n/a.`, `ТБД`, `см. ниже`, `???`
    // проходили молча, потому что не совпадали со словарём посимвольно.
    //
    // ⚠️ Пустая нормализация — отдельная ветвь, и она несущая. Значение из одних знаков препинания
    // и разделителей (`-`, `?`, `...`, `--`) схлопывается в пустую строку, которой в словаре нет;
    // без этой ветви правка «улучшила» бы сторожа так, что он перестал бы ловить простейшую
    // отговорку из всех. Поймано собственным набором в первый же прогон.
    const nv = normalizeValue(v);
    if (nv === '' || EVASIONS.has(nv)) {
      add('R3-evasion', key, `поле «${key}» заполнено отговоркой «${v}» — это плейсхолдер, а не ответ`, f.line);
    }
  }

  // ── R7 (механизм М2, «двигатель установлен на ракету») ───────────────────────────────────────
  //
  // `ON-REAL-PATH` отвечает на вопрос «видели ли мы этого сторожа работающим ТАМ, ГДЕ ХОДИТ
  // ВЛАДЕЛЕЦ, а не только в его собственном наборе». Наблюдение — это СОБЫТИЕ, случившееся в
  // момент времени; заявление без даты перепроверить нельзя, а непроверяемое заявление о
  // проверке — это и есть класс, который чинит весь эпик.
  //
  // Поэтому законны ровно две формы: честное `NOT YET` (долг признан и виден) либо ДАТА. «да»,
  // «проверено», «работает», «ок» отвергаются — они звучат как ответ и не являются им.
  //
  // Слово владельца, назвавшее механизм: «двигатель прошёл прожиг, все тесты зелёные — только его
  // забыли установить на ракету, которая уже на столе».
  if (block.kind === 'guard') {
    const rp = seen.get('ON-REAL-PATH');
    const v = rp ? rp.value.trim() : '';
    const notYet = /^not\s*yet\b/iu.test(v);
    const parsed = v ? parseObservationDate(v) : null;
    if (v && !notYet && !parsed) {
      add('R7-unauditable', 'ON-REAL-PATH',
        `ON-REAL-PATH: «${v.slice(0, 60)}» — ни даты, ни честного «NOT YET». Наблюдение без даты `
        + 'нельзя перепроверить, а непроверяемое заявление о проверке — это чинимый класс', rp.line);
    }
    // ── R8 (bugs/81): дата обязана быть НАСТОЯЩИМ днём и не лежать в будущем ────────────────────
    //
    // R7 спрашивал у строки «похожа ли ты на дату» и на этом останавливался, поэтому `2099-01-01`,
    // `2026-13-45` и `0000-00-00` проходили ворота молча. Поддельная дата при этом выглядит в
    // ревью честнее, чем `NOT YET`, — механизм, заведённый против недоказуемого «доказан», делал
    // ложь УДОБНЕЕ правды. Форма даты — модель угрозы; угроза — заявление о наблюдении, которого
    // не было.
    if (v && !notYet && parsed) {
      if (!parsed.valid) {
        add('R8-impossible-date', 'ON-REAL-PATH',
          `ON-REAL-PATH: «${parsed.text}» — такого дня не существует. Наблюдение датируется днём, `
          + 'который был, иначе это не улика, а её форма', rp.line);
      } else if (isFutureDate(parsed.date, now)) {
        add('R8-impossible-date', 'ON-REAL-PATH',
          `ON-REAL-PATH: «${parsed.text}» — дата в будущем. Наблюдение — событие, которое УЖЕ `
          + 'случилось; будущей датой закрывается долг, а не подтверждается проверка', rp.line);
      }
    }
  }

  // ── МЕХАНИЗМ М4 (`plans/78`): развилка — не собственность агента ──────────────────────────────
  //
  // Слово владельца: «НЕЛЬЗЯ ДОВЕРЯТЬ принятие решений на развилках ИИ модели и ИИ агенту».
  // Разведка `researches/27` дала форму: отрасль принуждает к разведке СЕКЦИЕЙ В ШАБЛОНЕ
  // («Alternatives Considered / Prior Art» у Squarespace, Background у Google), а не отдельным
  // процессом, — потому что пустую графу ВИДНО, а неспрошенный ритуал не вспомнит тот, кто про
  // него забыл. Наше преимущество перед отраслью: у неё графу читает ревьюер-человек, у нас
  // читает линтер в воротах сборки.
  if (block.kind === 'fork') {
    // R9: два и более варианта. Это «Alternatives Considered» в машинной форме, и оно ломает
    // ЛОЖНУЮ развилку: конструкция «A или B» разваливается ровно в момент, когда её пишут списком.
    // Ровно эта ложная развилка убила чёрный ящик 28 августа (EXP-0200) — «каждый такт или в
    // конце», при том что третий вариант стоил копейки.
    const o = seen.get('OPTIONS');
    if (o && o.value.trim()) {
      const parts = o.value.split(RE_OPTION_SPLIT).map((x) => x.trim()).filter(Boolean);
      if (parts.length < 2) {
        add('R9-single-option', 'OPTIONS',
          `OPTIONS несёт один вариант («${o.value.trim().slice(0, 50)}») — это не развилка, а `
          + 'уже принятое решение. Развилку выписывают СПИСКОМ: так видно третий вариант', o.line);
      }
    }
    // R10: `RECON` указывает на СУЩЕСТВУЮЩИЙ разведдок либо честно признаёт долг.
    //
    // Проверяется НАЛИЧИЕ ФАЙЛА, а не непустота поля, и это прямо из разведки: главный режим
    // смерти таких механизмов — «пишут, но не читают», к третьему месяцу сорок документов и
    // мёртвые ссылки. Для нашего проекта риск острее среднего: читатель — сессия с пустым
    // контекстом, и ссылка из места решения это её единственный механизм чтения.
    const r = seen.get('RECON');
    const rv = r ? r.value.trim() : '';
    if (rv && !/^not\s*yet\b/iu.test(rv)) {
      const m = /(researches\/[A-Za-z0-9_.-]+)/u.exec(rv);
      if (!m) {
        add('R10-dead-recon', 'RECON',
          `RECON: «${rv.slice(0, 50)}» не указывает на разведдок в researches/. Пересказ знания — `
          + 'не адрес знания; следующая сессия читает по ссылке, а не по памяти', r.line);
      } else if (!reconDocExists(m[1])) {
        add('R10-dead-recon', 'RECON',
          `RECON указывает на «${m[1]}», которого НЕТ на диске. Мёртвая ссылка хуже её отсутствия: `
          + 'она выглядит выполненным обязательством', r.line);
      }
    }
  }

  if (block.kind === 'forensic') {
    const d = seen.get('DURABLE-AT');
    if (d && d.value && FORBIDDEN_DURABLE.has(normalizeValue(d.value))) {
      add('R4-late-durable', 'DURABLE-AT',
        `DURABLE-AT: «${d.value.trim()}» — улика становится долговечной только при штатном конце. `
        + 'Событие, ради которого она существует, штатного конца не даёт (bugs/78)', d.line);
    }
  }

  // 🔴 ПРАВИЛО R6 «голый маркер» СНЯТО 2026-08-30 — его нашла мутация СОБСТВЕННОГО набора, в первый
  // же прогон, и это лучшее доказательство работоспособности механизма, какое можно было получить.
  //
  // Мутация «снять контроль голого маркера» дала НОЛЬ провалов: правило не покрывалось ни одной из
  // 108 фикстур. Причина — оно недостижимо по построению: маркер без полей означает, что все
  // обязательные поля отсутствуют, то есть R1 краснеет четыре раза раньше. R6 был ВТОРОЙ ПРИЧИНОЙ
  // для одного и того же красного — ровно то, против чего написан `bugs/71` («две причины для
  // одного красного расходятся в формулировках и порогах»), и семья [[EXP-0176]] (проверка слепа,
  // когда другая проверка её накрывает).
  //
  // Оставить его означало бы отгрузить правило, которое числится доказанным и не доказано ничем —
  // то есть повторить чинимый класс внутри инструмента, который его чинит.
  return out;
}

/**
 * Проверить целый текст. `now` пробрасывается, чтобы фикстуры границы «будущего» не зависели от
 * календаря машины: тест, зеленеющий или краснеющий от того, какой сегодня день, — не тест.
 */
export function checkText(text, file = '<memory>', opts = {}) {
  return parseBlocks(text).flatMap((b) => checkBlock(b, file, opts));
}

