/**
 * Привести значение поля к виду, в котором сверка со словарём смотрит на СМЫСЛ, а не на запись.
 *
 * Зачем существует (bugs/82). Оба словаря сверялись посимвольно, и всё, что не совпало буква в
 * букву, проходило молча: `close.` · `close;` · `«close»` · `on close` · `on_close` · `closing` ·
 * `при закрытии`. Множество писалось из головы, по-английски, в одной форме записи — то есть
 * моделировало не «класс значений, означающих поздно», а «те несколько строк, которые я вспомнил».
 * Точка в конце выводила значение из множества, не меняя смысла ни на йоту.
 *
 * ⚠️ ГРАНИЦА: нормализуется ВСЁ значение целиком и сверяется целиком. Слово словаря ВНУТРИ длинной
 * законной фразы обязано и дальше проходить молча — `GAP: поле n/a в отчёте драйвера не
 * заполняется` это законный ответ, а не отговорка, и краснеть на нём значило бы учить не писать
 * подробностей.
 *
 * @fork dictionary-vs-normalization
 * OPTIONS:  дописывать формы в словарь по мере находок · нормализовать значение перед сверкой ·
 *           перейти на морфологический разбор
 * COST:     сторож молчит на значении, ради запрета которого написан — и молчит ТИХО
 * RECON:    NOT YET — разведки о нормализации текста перед сверкой со словарём не проводилось;
 *           решение принято рассуждением о том, что список форм устареет так же, как устарел
 *           прошлый. Долг признан и виден
 * DECIDED:  нормализация. Список из ста форм устарел бы ровно так же, как список из десяти;
 *           морфология — третья сущность ради краевых случаев. Доказано мутациями F и H
 */
export function normalizeValue(v) {
  return String(v)
    .trim()
    .replace(/^[«"'`([]+/u, '')
    .replace(/[»"'`)\]]+$/u, '')
    .replace(/[.!?;:,]+$/u, '')
    // Верблюжий регистр — тоже разделитель: `onTrip` и `on-trip` означают одно.
    .replace(/(\p{Ll})(\p{Lu})/gu, '$1 $2')
    // Разделители УБИРАЮТСЯ, а не заменяются пробелом. Иначе у сверки остаётся третья форма записи:
    // `FixMe` дал бы `fix me`, а словарное `fixme` осталось бы слитным — и сторож перестал бы
    // видеть собственное слово. Поймано своим же набором.
    .replace(/[-_\s]+/gu, '')
    .toLowerCase();
}

