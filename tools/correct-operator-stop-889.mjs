#!/usr/bin/env node
// ОДНОРАЗОВЫЙ ИНСТРУМЕНТ — снять ЛОЖНОЕ ЗАВИСАНИЕ со ступени 2197 МГц / 785 мВ (`seq 889`).
//
// Полный разбор — `bugs/114` (AC3). Коротко: 2026-09-07 13:25:09 прогон `--sweep 2370→2167` был
// оборван ПО СЛОВУ ВЛАДЕЛЬЦА посреди ступени; убийство пришло снаружи и до обработчика сигнала не
// дошло, намерение осталось незакрытым — и следующий запуск (08.09 00:17) по правилу «намерение без
// вердикта = ЗАВИС» дописал `closeHangs` пустую запись без единого заполненного поля.
//
// ⚠️ ЭТО ВТОРОЙ СЛУЧАЙ ОДНОГО КЛАССА, а не первый: тот же путь дал `seq 695` 2026-08-24
// (`tools/correct-operator-stop-695.mjs`, `bugs/48`). Оба раза механизм РАБОТАЛ как задуман —
// `closeAsOperatorStop` подключён к SIGINT/SIGTERM/SIGBREAK и закрывает штатную остановку честно.
// Отказывает не он: ЖЁСТКОЕ убийство дерева процессов снаружи не доставляет ловимого сигнала
// НИКОГДА и не должно (ловушка T5 держит это свойство нарочно). Поэтому лечение класса — не трогать
// правило и не ослаблять путь зависания, а дать остановке ДРУГУЮ дверь; она заведена в `bugs/114`.
//
// ⚠️ ПОЧЕМУ ЭТО ПОПРАВКА, А НЕ `close-operator-stop.mjs`: там закрывают ОСИРОТЕВШЕЕ намерение, у
// которого вердикта ещё нет. Здесь вердикт уже написан (`outcome: "hung"`, `at: null`), сирот ноль.
// Закрытую запись переатрибутирует только `writeCorrection`, и она требует улику — она ниже.
//
// 🟢 ПОЧЕМУ ЭТО БЕЗОПАСНО И НЕ ОТКРЫВАЕТ КАРТЕ ПЛОХОЕ НАПРЯЖЕНИЕ: пол 2197 МГц / 785 мВ стоит НЕ НА
// ЭТОЙ записи. Его поставил `seq 886` пятьюдесятью секундами раньше — НАСТОЯЩЕЕ зависание с полным
// набором полей и сработавшей аварийной защитой. Поправка не снимает пол; она снимает ВТОРУЮ его
// половину, из-за которой сработал единственный аварийный тормоз, оставленный владельцем себе, —
// «два зависания подряд». Фабриковать его половину из решения человека значит расшатывать тормоз.
//
// Инструмент ничего не стирает: поправка ДОПИСЫВАЕТСЯ, оригинальная строка остаётся на диске
// читаемой навсегда (правка улик руками — это `bugs/08`). Повторный запуск безвреден.
//
// AUTH: критерий приёмки AC3 тикета `bugs/114`, заведённого сессией 88. Владельцу вопрос не
// задавался по его правилу 07.09 (`interviews/028`): ответ не меняет того, что он увидит.
//
// [NOT-TESTED] сам по себе; механизм, который он зовёт, доказан блоками `journal --selftest`.
import {
  openJournal, writeCorrection, hangFloors, blockedRungs, readJournal, RUNG_OUTCOME, SWEEP_DIR,
} from '../automation-engine/lib/sweep-journal.mjs';
import { resolve as entryResolve } from 'node:path';
import { fileURLToPath as entryPath } from 'node:url';

async function main(argv) {
  if (argv.includes('--help') || argv.includes('-h')) {
    console.log('Использование: node tools/correct-operator-stop-889.mjs');
    console.log('  Снимает ЛОЖНОЕ зависание seq 889 (2197 МГц / 785 мВ) поправкой. Разбор — bugs/114.');
    console.log('  Повторный запуск безвреден: поправки идемпотентны по seq.');
    return 0;
  }

  const SEQ = 889;

  // УЛИКА. Обязательное поле: поправка без неё — это правка улик одной строкой ниже (`bugs/08`).
  // Четыре независимых свидетеля, и ни один не является рассуждением о том, «как оно наверное было».
  const EVIDENCE = '2197 МГц / 785 мВ: ЭТО БЫЛА ОСТАНОВКА ПО СЛОВУ ВЛАДЕЛЬЦА, А НЕ ВТОРОЕ ЗАВИСАНИЕ '
    + 'МАШИНЫ. '
    + 'Свидетель 1 — ЛОГ ПРОГОНА ОБРЫВАЕТСЯ НА СЕРЕДИНЕ ЭТОЙ СТУПЕНИ. '
    + 'runs/logs/peremer-20260907-131843/2026-09-07T13-18-43+03-00.log, последняя строка файла — '
    + '«ПРОБЫ ПРОШЛОГО ТАКОГО ЖЕ ПРОЖИГА: убраны в …cap-2197-742-2026-09-07T10-24-15-140Z.jsonl», '
    + 'то есть намерение записано и дальше НЕТ НИЧЕГО. '
    + 'Свидетель 2 — ЗАВИСАНИЕ НА ЭТОЙ КАРТЕ ГРОМКОЕ, И ТА ЖЕ СТУПЕНЬ ЭТО ПОКАЗАЛА ЗА 50 СЕКУНД ДО. '
    + 'Настоящее зависание seq 886 (13:24:19) напечатало в тот же лог четыре строки: красный блок '
    + 'атома CRASH, «СРАБОТАЛА АВАРИЙНАЯ ЗАЩИТА (САЗ) … МАШИНА ЖИВА», «⏳ ЖДУ АПВ», «✅ АПВ УСПЕШНО» — '
    + 'и прогон ПРОДОЛЖИЛСЯ. За весь прогон защита срабатывала 5 раз и каждый раз была слышна. '
    + 'У seq 889 в логе НЕ НАПЕЧАТАНО НИ ОДНОЙ из этих строк, а защита была на посту. '
    + 'Свидетель 3 — У ПРОГОНА НЕТ ИТОГОВОЙ СВОДКИ ВООБЩЕ: строк «КОД ВОЗВРАТА», «ПОКРЫТИЕ:», '
    + '«РАЗВЁРТКА «…»» в файле НОЛЬ. Прогон, дошедший до конца хоть как-нибудь, свою сводку пишет; '
    + 'этот был прекращён снаружи. '
    + 'Свидетель 4 — СЛОВО ВЛАДЕЛЬЦА, записанное в тот же день: STATUS.md, сессия 86 — '
    + '«--sweep 2370→2167, оборван по слову владельца на 2197 МГц». '
    + 'Форма самой записи довершает картину: at=null, decidedBy=null, deliveredMhz=null, '
    + 'redBlocks отсутствуют — подпись closeHangs на следующем запуске, а не замер. '
    + 'ЧТО ПОПРАВКА МЕНЯЕТ, А ЧТО НЕТ: пол 2197 МГц / 785 мВ ОСТАЁТСЯ — он стоит на seq 886, '
    + 'настоящем зависании. Снимается только ВТОРАЯ его половина, из-за которой ступень попала под '
    + 'аварийную остановку «два зависания подряд» — единственный тормоз, оставленный владельцем себе.';

  const journal = openJournal({ dir: SWEEP_DIR });
  const before = readJournal(journal).records;
  const floorsBefore = hangFloors(before);
  const blockedBefore = blockedRungs(before);

  console.log('ДО ПОПРАВКИ');
  console.log(`   пол 2197 МГц: ${floorsBefore.get(2197)?.voltageMv ?? '—'} мВ (seq ${floorsBefore.get(2197)?.seq ?? '—'})`);
  console.log(`   заблокировано двумя зависаниями подряд: ${[...blockedBefore].map((b) => (typeof b === 'object' ? `${b.frequencyMhz} МГц / ${b.voltageMv} мВ` : String(b))).join(' · ') || 'ничего'}`);

  const rec = writeCorrection(journal, {
    seq: SEQ,
    // ОСТАНОВ ОПЕРАТОРА, а не наша смерть: писатель не падал, его прекратили по слову человека.
    outcome: RUNG_OUTCOME.STOPPED,
    at: new Date().toISOString(),
    correctedBy: 'bugs/114 AC3, сессия 89',
    why: EVIDENCE,
  });
  console.log(`\nПОПРАВЛЕНО seq ${SEQ}: ${rec.frequencyMhz} МГц / ${rec.voltageMv} мВ -> ${rec.outcome}`);

  const after = readJournal(journal).records;
  const floorsAfter = hangFloors(after);
  const blockedAfter = blockedRungs(after);
  console.log('\nПОСЛЕ ПОПРАВКИ');
  console.log(`   пол 2197 МГц: ${floorsAfter.get(2197)?.voltageMv ?? '—'} мВ (seq ${floorsAfter.get(2197)?.seq ?? '—'})`);
  console.log(`   заблокировано двумя зависаниями подряд: ${[...blockedAfter].map((b) => (typeof b === 'object' ? `${b.frequencyMhz} МГц / ${b.voltageMv} мВ` : String(b))).join(' · ') || 'ничего'}`);

  // СТОРОЖ СОБСТВЕННОГО ОБЕЩАНИЯ: поправка обязана СНЯТЬ блокировку и ОСТАВИТЬ пол. Проверяется
  // прогоном здесь же, а не заявляется в шапке: заявление о том, что «стену не открыл», стоит ровно
  // столько же, сколько заявление «протестировано».
  const floorKept = floorsAfter.get(2197)?.voltageMv === floorsBefore.get(2197)?.voltageMv;
  console.log(`\nПОЛ СОХРАНЁН: ${floorKept ? 'ДА — поправка сняла блокировку, а не стену' : '🔴 НЕТ — это дефект поправки'}`);
  return floorKept ? 0 : 1;
}

// СТОРОЖ ВХОДА — прибор исполняется ТОЛЬКО как программа, никогда при импорте (`bugs/95`).
if (process.argv[1] && entryResolve(process.argv[1]) === entryResolve(entryPath(import.meta.url))) {
  main(process.argv.slice(2)).then((code) => process.exit(code));
}
