#!/usr/bin/env node
// ОДНОРАЗОВЫЙ ИНСТРУМЕНТ СЕССИИ 47 — снять ЛОЖНОЕ ЗАВИСАНИЕ со ступени 2355 МГц / 845 мВ (`seq 695`).
//
// Полный разбор — `bugs/48`. Коротко: 2026-08-24 00:2x прогон был остановлен ПО СЛОВУ ВЛАДЕЛЬЦА
// («СТОП»), агент убил его ЖЁСТКО (`TaskStop`), обработчик `SIGINT` до дела не дошёл, намерение
// осталось незакрытым — и следующий запуск по правилу R15b прочитал его как зависание машины.
// Машина не висла ни секунды: карта после убийства была чисто откачена сторожем (128 точек в ноль).
//
// ⚠️ ПОЧЕМУ ЭТО ПОПРАВКА, А НЕ `close-operator-stop.mjs`. Тот инструмент закрывает ОСИРОТЕВШЕЕ
// намерение — то, у которого вердикта ещё нет. Здесь вердикт уже написан (`outcome: "hung"`,
// `at: null` — его дописал `closeHangs` на следующем запуске), сирот в журнале ноль. Закрытую
// запись переатрибутирует только `writeCorrection`, и она требует улику — та ниже.
//
// Инструмент ничего не стирает: поправка ДОПИСЫВАЕТСЯ, оригинальная строка `ЗАВИС` остаётся на диске
// читаемой навсегда (правка улик руками — это `bugs/08`). Повторный запуск безвреден.
//
// AUTH: владелец, чат 2026-08-24, дословно — «1 - снимай».
//
// [NOT-TESTED] сам по себе; механизм, который он зовёт, доказан блоками `journal --selftest`.
import {
  openJournal, writeCorrection, hangFloors, readJournal, RUNG_OUTCOME, SWEEP_DIR,
} from '../automation-engine/lib/sweep-journal.mjs';

const SEQ = 695;

// УЛИКА. Обязательное поле: поправка без неё — это правка улик одной строкой ниже (`bugs/08`).
// Три независимых свидетеля, и ни один не является рассуждением о том, «как оно наверное было».
const EVIDENCE = '2355 МГц / 845 мВ: ЭТО БЫЛА ОСТАНОВКА ПО СЛОВУ ВЛАДЕЛЬЦА, А НЕ ЗАВИСАНИЕ МАШИНЫ. '
  + 'Свидетель 1 — владелец сказал «СТОП» в чате, агент убил прогон снаружи (TaskStop, убийство '
  + 'дерева процессов). Такое убийство до обработчика SIGINT не доходит НИКОГДА и не должно (ловушка '
  + 'T5 держит это свойство нарочно), поэтому вердикта не появилось, и closeHangs на следующем '
  + 'запуске записал ЗАВИС — честно по построению и неверно по факту. '
  + 'Свидетель 2 — карта после убийства откачена сторожем ЧИСТО: 128 точек в ноль, watchdog --status '
  + '«НЕ ВЗВЕДЁН, ничего не держит». Зависшая машина откат не исполняет — это и есть R10. '
  + 'Свидетель 3 — разрыв во времени до следующей записи журнала 2 мин 22 с (00:21:42 -> 00:24:04), '
  + 'то есть НЕ цикл перезагрузки: настоящие зависания этой карты дали 16 мин 54 с (2887/865) и '
  + 'переход через сутки (2842/845). '
  + 'Цена, уже уплаченная: следующий прогон ПРОПУСТИЛ 2355 МГц целиком по ложному полу, покрытие '
  + '0 из 7. Поправка снимает стену; частота проходит свою лестницу заново под наблюдением владельца.';

const journal = openJournal({ dir: SWEEP_DIR });
const before = hangFloors(readJournal(journal).records);
console.log('ПОЛ ЗАВИСАНИЯ ДО ПОПРАВКИ:');
for (const [mhz, v] of [...before].sort((a, b) => b[0] - a[0])) {
  console.log(`   ${mhz} МГц -> ${v.voltageMv} мВ (seq ${v.seq})`);
}

const rec = writeCorrection(journal, {
  seq: SEQ,
  // ОСТАНОВ ОПЕРАТОРА, а не наша смерть: писатель не падал, его убили штатно и по слову человека.
  outcome: RUNG_OUTCOME.STOPPED,
  at: new Date().toISOString(),
  correctedBy: 'сессия 47, по слову владельца 2026-08-24 «1 - снимай»',
  why: EVIDENCE,
});
console.log(`\nПОПРАВЛЕНО seq ${SEQ}: ${rec.frequencyMhz} МГц / ${rec.voltageMv} мВ -> ${rec.outcome}`);

const after = hangFloors(readJournal(journal).records);
console.log('\nПОЛ ЗАВИСАНИЯ ПОСЛЕ ПОПРАВКИ:');
for (const [mhz, v] of [...after].sort((a, b) => b[0] - a[0])) {
  console.log(`   ${mhz} МГц -> ${v.voltageMv} мВ (seq ${v.seq})`);
}
console.log(`\nбыло полов ${before.size}, стало ${after.size} — снято ${before.size - after.size}`);
