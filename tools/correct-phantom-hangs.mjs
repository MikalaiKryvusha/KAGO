#!/usr/bin/env node
// ОДНОРАЗОВЫЙ ИНСТРУМЕНТ СЕССИИ 37 — снять стену с двух ФАНТОМНЫХ зависаний боевого журнала.
//
// Полный разбор, почему эти две записи не о карте, — в шапке `sweep-journal.writeCorrection`
// и в `bugs/20`. Коротко: 2026-08-16 прогон дважды убили НАШИ ЖЕ механизмы (`bugs/19` — пульс
// сторожа, `bugs/21` — хук уборки), а журнал записал обе смерти как зависание машины. `bugs/20`
// прописал лечение «пусть прогон перемерит частоту», но R18 назавтра сделал записанное зависание
// СТЕНОЙ, и перемер стал невозможен: фантом сам запрещает спуск, который бы его опроверг.
//
// Инструмент ничего не стирает: поправка ДОПИСЫВАЕТСЯ, оригинальные строки `ЗАВИС` остаются на
// диске читаемыми навсегда (журнал дописываемый — правка улик руками это `bugs/08`).
//
// Запускать один раз. Повторный запуск безвреден — поправки идемпотентны по `seq`.
//
// [NOT-TESTED] сам по себе; механизм, который он зовёт, доказан 7 блоками и 2 мутациями
// в `npm run journal -- --selftest`.
import {
  openJournal, writeCorrection, hangFloors, readJournal, RUNG_OUTCOME, SWEEP_DIR,
} from '../automation-engine/lib/sweep-journal.mjs';

// Улика — общая для обеих ступеней, потому что обе принадлежат одной сессии и одному классу.
const EVIDENCE = 'СЕССИЯ 30 (2026-08-16 16:0x-18:1x): STATUS о ней дословно — «Карта за всю сессию '
  + 'не сбоила НИ РАЗУ. Все прожиги — PASS», а прогон убивали дважды свои же механизмы (bugs/19 — '
  + 'сердцебиение сторожа, EPERM на renameSync; bugs/21 — хук уборки). Обе ступени названы поимённо '
  + 'в bugs/20 и в списке открытых багов STATUS как выдуманные отказы. Разрыв во времени до '
  + 'следующей записи журнала — минуты, а не цикл перезагрузки: настоящие зависания этой карты дали '
  + '16 мин 54 с (2887/865) и переход через сутки (2842/845). Лечение bugs/20 предписывало ПЕРЕМЕР, '
  + 'но R18 (2026-08-17) сделал записанное зависание стеной и перемер запретил — поправка снимает '
  + 'стену, и частота проходит свою лестницу заново под наблюдением владельца.';

const TARGETS = [
  [274, '2542 МГц / 895 мВ'],
  [294, '2775 МГц / 965 мВ'],
];

const journal = openJournal({ dir: SWEEP_DIR });
const before = hangFloors(readJournal(journal).records);
console.log('ПОЛ ЗАВИСАНИЯ ДО ПОПРАВКИ:');
for (const [mhz, v] of [...before].sort((a, b) => b[0] - a[0])) {
  console.log(`   ${mhz} МГц -> ${v.voltageMv} мВ (seq ${v.seq})`);
}

for (const [seq, what] of TARGETS) {
  const rec = writeCorrection(journal, {
    seq,
    outcome: RUNG_OUTCOME.CRASHED,
    at: new Date().toISOString(),
    correctedBy: 'сессия 37, по улике сессии 30',
    why: `${what}: ЭТО БЫЛА НАША СМЕРТЬ, А НЕ КАРТЫ. ${EVIDENCE}`,
  });
  console.log(`\nПОПРАВЛЕНО seq ${seq}: ${rec.frequencyMhz} МГц / ${rec.voltageMv} мВ -> ${rec.outcome}`);
}

const after = hangFloors(readJournal(journal).records);
console.log('\nПОЛ ЗАВИСАНИЯ ПОСЛЕ ПОПРАВКИ:');
for (const [mhz, v] of [...after].sort((a, b) => b[0] - a[0])) {
  console.log(`   ${mhz} МГц -> ${v.voltageMv} мВ (seq ${v.seq})`);
}
console.log(`\nбыло полов ${before.size}, стало ${after.size} — снято ${before.size - after.size}`);
